export function explain(code: string, lang: Lang): string {
  return (
    errors[code]?.[lang === 'tr' ? 0 : 1] ??
    (lang === 'tr'
      ? 'İşlem tamamlanamadı. Yeni değişiklik yapmadan durduruldu; ayrıntı kodunu kontrol et.'
      : 'The operation could not complete. It stopped before further changes; review the detail code.')
  );
}
export function phase(phase: string, lang: Lang): string {
  const map: Record<string, [string, string]> = {
    preparing: ['Hazırlanıyor', 'Preparing'],
    launching: ['Replay bekleniyor', 'Waiting for replay'],
    warming: ['Sahne hazırlanıyor', 'Warming the scene'],
    capturing: ['Kareler ölçülüyor', 'Measuring frames'],
    comparing: ['Sonuçlar karşılaştırılıyor', 'Comparing results'],
    applying: ['Doğrulanmış ayar uygulanıyor', 'Applying confirmed settings'],
    complete: ['Tamamlandı', 'Completed'],
    failed: ['Deney durdu', 'Experiment stopped'],
    canceled: ['Durduruldu', 'Stopped'],
  };
  return map[phase]?.[lang === 'tr' ? 0 : 1] ?? phase;
}
